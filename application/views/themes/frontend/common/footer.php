        $(document).ready(function() {
        // Timer function for OTP
        window.userTimerstartFooter = function(time) {
           var countDownDate = new Date().getTime() +  time * 60 * 1000;
            var x = setInterval(function() {
              var now = new Date().getTime();
              var distance = countDownDate - now;
              var hours = Math.floor((distance % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60));
              var minutes = Math.floor((distance % (1000 * 60 * 60)) / (1000 * 60));
              var seconds = Math.floor((distance % (1000 * 60)) / 1000);
              $('#timer_footer').html( minutes + ":" + seconds);
              if (distance < 0) {
                $('#createbookingOtpPopup').find('.resend-otp-text').hide();
                $('#createbookingOtpPopup').find('.resend-otp-link').show();
                $('#timer_footer').html("0:00");
                clearInterval(x);
                return false;
              }
            }, 1000);
        }
        
        // Handle brand change and load models
        window.handleChangePop = async function(e) {
            const id = $(e).val();
            $.ajax({
                url:'<?php echo base_url(); ?>Home_public/getModelByBrandId',
                type: 'POST',
                data : {
                    'id':id
                },
                dataType: 'JSON',
                success:function(res){
                    if(res.status == 200){
                        var htmldata = '<option value="">SELECT MODEL</option>';
                        res.data.forEach(function (value) {
                            htmldata += '<option value="'+value.id+'">'+value.name+'</option>';
                        });
                        $("#contact_formPop").find('.modal_id').html(htmldata);
                    }else{
                        var htmldata = '<option value=""></option>';
                        $("#contact_formPop").find('.modal_id').html(htmldata);
                    }
                }
            });
        }
        
        // Set service category when modal opens - MUST run before other handlers
        $(document).on('show.bs.modal', '#cta', function (event) {
          // Get category from the button that triggered the modal
          const button = $(event.relatedTarget);
          let category = button.data('category');
          
          // If no category from button, try to get from the link text
          if (!category && button.length) {
            category = button.text().trim();
          }
          
          // If still no category, get the active category from the services page
          if (!category) {
            const activeCategory = $('.wrapper .owl_1 .nav-item.active a').text().trim();
            if (activeCategory) {
              category = activeCategory;
            }
          }
          
          // Ensure modal heading is correct (only the main heading, not OTP heading)
          const modalHeading = $('#cta .modal-body h3#modal_main_heading');
          if (modalHeading.length && modalHeading.text().trim() !== 'Book now') {
            modalHeading.text('Book now');
          }
          
          // Set the category in the form
          if (category) {
            $('#service_category').val(category);
            $('#service').val(category);
            console.log('Category set to:', category);
          } else {
            console.log('No category found');
          }
        });
        
        // Contact form submission - Send OTP
        // ALWAYS attach handler - remove any existing handlers first
        // This ensures OTP flow works on all pages
        $("#contact_formPop").off('submit').on('submit', function(e){
          e.preventDefault();
              e.stopImmediatePropagation(); // Prevent other handlers from firing
              
              // Prevent double submission
              if ($(this).data('submitting')) {
                return false;
              }
              $(this).data('submitting', true);
              
              const brand_id = $("#contact_formPop").find('.brand_id').val();
              const modal_id = $("#contact_formPop").find('.modal_id').val();
              const service = $("#contact_formPop").find('.service').val();
              const full_name = $("#contact_formPop").find('.full_name').val();
              const phone_number = $("#contact_formPop").find('.phone_number').val();
              const message = $("#contact_formPop").find('.message').val();
              
              if (!phone_number || phone_number.length !== 10) {
                $(this).data('submitting', false);
                $.notify('Please enter a valid 10-digit phone number', 'error');
            return false;
          }
        
              $("#contact_formPop").find('#contatSubmit').prop('disabled', true).html('Sending OTP...');
          
              // Send OTP first
          $.ajax({
              url:'<?php echo base_url(); ?>Home_public/sendOtp',
              type: 'POST',
              data : {
                  'brand_id': brand_id,
                  'modal_id': modal_id,
                  'full_name': full_name,
                  'phone_number' : phone_number,
                  'message' : message,
                  'service': service
              },
              dataType: 'JSON',
              success:function(res){
                      $("#contact_formPop").data('submitting', false);
                  if(res.status == 200){
                        $.notify('OTP sent successfully', 'success');
                        
                        // Hide main form heading and show OTP heading
                        $('#modal_main_heading_footer').hide();
                        $('#modal_otp_heading_footer').show();
                        
                        // Hide contact form and show OTP form
                        $("#contact_formPop").hide();
                        $("#createbookingOtpPopup").show();
                        
                        // Populate hidden fields in OTP form
                        $("#createbookingOtpPopup").find('.entered_phone_no').html(phone_number);
                        $("#createbookingOtpPopup").find('#mobile_footer').val(phone_number);
                        $("#createbookingOtpPopup").find('#service_footer').val(service);
                        $("#createbookingOtpPopup").find('#brand_id_footer').val(brand_id);
                        $("#createbookingOtpPopup").find('#modal_id_footer').val(modal_id);
                        $("#createbookingOtpPopup").find('#full_name_footer').val(full_name);
                        $("#createbookingOtpPopup").find('#message_footer').val(message);
                        
                        // Start OTP timer
                        userTimerstartFooter(1);
                        
                        $("#contact_formPop").find('#contatSubmit').prop('disabled', false).html('Submit');
                  }else{
                    $.notify(res.message, 'error');
                        $("#contact_formPop").find('#contatSubmit').prop('disabled', false).html('Submit');
                  }
              },
              error: function(error) {
                    $("#contact_formPop").data('submitting', false);
                    $.notify('Error sending OTP', 'error');
                    $("#contact_formPop").find('#contatSubmit').prop('disabled', false).html('Submit');
              }
          });
        });
        
        // OTP verification and form submission
        $('#createbookingOtpPopup').off('submit').on('submit', function(e){
          e.preventDefault();
          $('.error_class').remove();
          
          const brand_id = $("#createbookingOtpPopup").find('#brand_id_footer').val();
          const modal_id = $("#createbookingOtpPopup").find('#modal_id_footer').val();
          const full_name = $("#createbookingOtpPopup").find('#full_name_footer').val();
          const phone_number = $("#createbookingOtpPopup").find('#mobile_footer').val();
          const message = $("#createbookingOtpPopup").find('#message_footer').val();
          const service = $("#createbookingOtpPopup").find('#service_footer').val();
          const otp = $('#createbookingOtpPopup').find('#otp').val();
          
          if (!otp) {
            $('#createbookingOtpPopup').find('#otp').after('<div class="error_class" style="color:red;">OTP is required</div>');
            $('#createbookingOtpPopup').find('#otp').focus();
            return false;
          }
        
          $("#createbookingOtpPopup").find('button[type="submit"]').prop('disabled', true);
          $("#createbookingOtpPopup").find('button[type="submit"]').html('Verifying...');
          
          $.ajax({
              url:'<?php echo base_url(); ?>Home_public/saveContactForm',
              type: 'POST',
              data : {
                  'brand_id': brand_id,
                  'modal_id': modal_id,
                  'full_name': full_name,
                  'phone_number' : phone_number,
                  'message' : message,
                  'service' : service,
                  'otp' : otp
              },
              dataType: 'JSON',
              success:function(res){
                  if(res.status == 200){
                      $.notify('OTP verified successfully!', 'success');
                      
                      // Redirect to thank you page
                      window.location.href = '<?php echo base_url(); ?>thankyou';
                  }else{
                      $.notify(res.message || 'Invalid OTP. Please try again.', 'error');
                      $("#createbookingOtpPopup").find('button[type="submit"]').prop('disabled', false);
                      $("#createbookingOtpPopup").find('button[type="submit"]').html('Verify');
                  }
              },
              error: function(error) {
                $.notify('Error verifying OTP', 'error');
                $("#createbookingOtpPopup").find('button[type="submit"]').prop('disabled', false);
                $("#createbookingOtpPopup").find('button[type="submit"]').html('Verify');
              }
          });
        });
        
        // Resend OTP function
        window.resendOTPFooter = function() {
          try{
            const phone_number = $("#createbookingOtpPopup").find('#mobile_footer').val();
            const service = $("#createbookingOtpPopup").find('#service_footer').val();
            $.ajax({
                  url:'<?php echo base_url(); ?>Home_public/sendOtp',
                  type: 'POST',
                  data : {
                      'phone_number' : phone_number,
                      'message' : 'Booking request for ' + service
                  },
                  dataType: 'JSON',
                  success:function(res){
                      if(res.status == 200){
                       $("#createbookingOtpPopup").find('.entered_phone_no').html(phone_number);
                        $.notify('OTP resent successfully','success');
                         $('#createbookingOtpPopup').find('.resend-otp-text').show(0);
                        $('#createbookingOtpPopup').find('.resend-otp-link').hide(0);
                        userTimerstartFooter(1);
                      }else{
                        $.notify(res.message || 'Failed to resend OTP', 'error');
                        console.log(res.message);
                      }
                  },
                  error: function (error){
                    console.log(error);
                    $.notify('Error resending OTP', 'error');
                  }
            });
          }catch(error){
            console.log(error);
          }
        }
        
        // Reset modal on close
        $('#cta').on('hidden.bs.modal', function () {
          $("#contact_formPop")[0].reset();
          $("#createbookingOtpPopup")[0].reset();
          
          // Show main form and hide OTP form
          $("#contact_formPop").show();
          $("#createbookingOtpPopup").hide();
          
          // Show main heading and hide OTP heading
          $('#modal_main_heading_footer').show();
          $('#modal_otp_heading_footer').hide();
          
          // Reset buttons
